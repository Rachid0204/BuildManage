import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import {
  ALL_USER_GUIDES,
  GUIDE_ROLES,
  getGuidesByRole,
  type GuideRole,
  type UserGuideArticle,
} from '../data/userGuides/index';

const ROOT = resolve(import.meta.dirname, '..');
const OUT_DIR = join(ROOT, 'docs', 'guides');

function renderArticleMarkdown(article: UserGuideArticle, idx: number): string {
  const lines: string[] = [];
  lines.push(`## ${idx + 1}. ${article.titleFr}`);
  lines.push(`> **AR:** ${article.titleAr}`);
  lines.push('');
  lines.push(
    `**Catégorie :** ${article.categoryFr} · **Durée estimée :** ~${article.estimatedMinutes} min`,
  );
  lines.push('');
  lines.push(article.summaryFr);
  lines.push('');
  if (article.prerequisitesFr?.length) {
    lines.push('### Prérequis');
    for (const pre of article.prerequisitesFr) {
      lines.push(`- ${pre}`);
    }
    lines.push('');
  }
  lines.push('### Étapes pas à pas');
  lines.push('');
  article.steps.forEach((step, sIdx) => {
    lines.push(`#### Étape ${sIdx + 1} — ${step.titleFr}`);
    lines.push('');
    lines.push(step.bodyFr);
    lines.push('');
    if (step.tipFr) {
      lines.push(`> **Astuce :** ${step.tipFr}`);
      lines.push('');
    }
    if (step.screenshot) {
      const relPath = `../../public${step.screenshot.src}`;
      lines.push(`![${step.screenshot.altFr}](${relPath})`);
      if (step.screenshot.captionFr) {
        lines.push(`*${step.screenshot.captionFr}*`);
      }
      lines.push('');
    }
  });
  if (article.legalNoteFr) {
    lines.push(`> **Conformité Maroc (Loi 18-00 / CGI) :** ${article.legalNoteFr}`);
    lines.push('');
  }
  if (article.faq?.length) {
    lines.push('### Questions fréquentes');
    lines.push('');
    for (const f of article.faq) {
      lines.push(`- **${f.qFr}** — ${f.aFr}`);
    }
    lines.push('');
  }
  lines.push('---');
  lines.push('');
  return lines.join('\n');
}

function renderRoleManual(role: GuideRole): string {
  const meta = GUIDE_ROLES.find((r) => r.id === role)!;
  const articles = getGuidesByRole(role);
  const lines: string[] = [
    `<!-- AUTO-GENERATED by npm run docs:guides from data/userGuides/ — DO NOT EDIT MANUALLY -->`,
    `# Guide d’Utilisation — ${meta.labelFr}`,
    `> **AR :** دليل الاستخدام — ${meta.labelAr}`,
    '',
    meta.descriptionFr,
    '',
    '## Sommaire',
    '',
    ...articles.map(
      (a, idx) =>
        `${idx + 1}. [${a.titleFr}](#${idx + 1}-${a.titleFr
          .toLowerCase()
          .normalize('NFD')
          .replace(/[\u0300-\u036f]/g, '')
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/^-|-$/g, '')})`,
    ),
    '',
    '---',
    '',
    ...articles.map((a, idx) => renderArticleMarkdown(a, idx)),
  ];
  return lines.join('\n');
}

function renderMasterIndex(): string {
  const lines: string[] = [
    `<!-- AUTO-GENERATED by npm run docs:guides from data/userGuides/ — DO NOT EDIT MANUALLY -->`,
    '# Guides d’Utilisation BuildManage / Syndik Maroc',
    '',
    `Ce dossier regroupe les **${ALL_USER_GUIDES.length} guides pas à pas** (avec captures d’écran réelles générées automatiquement via \`npm run docs:screenshots\`) couvrant les 4 portails de la plateforme.`,
    '',
    '## Manuels par rôle',
    '',
    '| Rôle | Nombre de guides | Manuel Markdown |',
    '|---|---:|---|',
    ...GUIDE_ROLES.map((meta) => {
      const count = getGuidesByRole(meta.id).length;
      return `| **${meta.labelFr}** (${meta.labelAr}) | ${count} | [docs/guides/${meta.id}.md](./${meta.id}.md) |`;
    }),
    '',
    '## Régénérer les captures d’écran et la documentation',
    '',
    '```bash',
    'npm run build',
    'npm run docs:screenshots',
    'npm run docs:guides',
    'npm run test:user-guides',
    '```',
    '',
  ];
  return lines.join('\n');
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'README.md'), renderMasterIndex(), 'utf8');
for (const roleMeta of GUIDE_ROLES) {
  writeFileSync(
    join(OUT_DIR, `${roleMeta.id}.md`),
    renderRoleManual(roleMeta.id),
    'utf8',
  );
}

console.log(
  `Exported ${ALL_USER_GUIDES.length} user guides across ${GUIDE_ROLES.length} role manuals to docs/guides/.`,
);
