import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';
import { chromium, expect } from '@playwright/test';

const emulator = process.env.FIREBASE_AUTH_EMULATOR_HOST;
assert.ok(emulator?.startsWith('127.0.0.1:'), 'Run with the local demo Auth emulator');
const directory = mkdtempSync(join(tmpdir(), 'buildmanage-auth-browser-'));
const listener = createServer();
await new Promise<void>(resolve => listener.listen(0, '127.0.0.1', resolve));
const port = (listener.address() as any).port;
await new Promise<void>(resolve => listener.close(() => resolve()));
const base = `http://127.0.0.1:${port}`;
const child = spawn(process.execPath, ['--import', './tests/helpers/networkGuard.mjs', '--import', 'tsx', 'server.ts'], {
  env: { ...process.env, NODE_ENV: 'development', PORT: String(port), GOOGLE_CLOUD_PROJECT: 'demo-buildmanage',
    SYNDIK_AUTH_PROVIDER: 'firebase', SYNDIK_STATE_BACKEND: 'file', SYNDIK_DATA_DIR: directory,
    SYNDIK_SERVER_SECRET: 'synthetic-auth-browser-secret-1234567890', PUBLIC_APP_URL: base,
    FIREBASE_API_KEY: 'demo-key', VITE_FIREBASE_API_KEY: 'demo-key', VITE_FIREBASE_PROJECT_ID: 'demo-buildmanage',
    VITE_FIREBASE_AUTH_DOMAIN: 'demo-buildmanage.firebaseapp.com', VITE_USE_MOCK_DATA: 'true', VITE_FIRESTORE_DATABASE_ID: '(default)', VITE_FIREBASE_AUTH_EMULATOR_URL: `http://${emulator}`,
    SENDGRID_API_KEY: '', SENDGRID_FROM_EMAIL: '' }, stdio: ['ignore', 'pipe', 'pipe'],
});
const exited = once(child, 'exit'); let logs = ''; let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
child.stdout.on('data', bytes => { logs += bytes; }); child.stderr.on('data', bytes => { logs += bytes; });
try {
  for (let i = 0; i < 100; i++) {
    try { if ((await fetch(`${base}/api/health`)).ok) break; } catch {}
    if (child.exitCode !== null) throw new Error(logs);
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) });
  const page = await browser.newPage({ serviceWorkers: 'block' });
  await page.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  const failures: string[] = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto(`${base}/login?mode=syndic-signup`);
  const isolation = await page.evaluate(async () => {
    const modulePath = '/firebase/config.ts';
    const module = await import(modulePath);
    return { project: module.firebaseConfig.projectId, emulator: module.auth.emulatorConfig?.host,
      directCloudReadsDisabled: module.isMock };
  });
  assert.deepEqual(isolation, { project: 'demo-buildmanage', emulator: '127.0.0.1', directCloudReadsDisabled: true },
    'Fail before entering any test data unless Firebase Auth is local and direct Cloud reads are disabled');
  await page.getByPlaceholder('Ex: Cabinet Atlas Gestion').fill('Firebase browser cabinet');
  await page.getByPlaceholder('Ex: Karim Tazi').fill('Firebase browser manager');
  await page.getByPlaceholder('06 61 23 45 67').fill('0661234567');
  await page.getByPlaceholder('contact@moncabinet.ma', { exact: true }).fill('browser@example.test');
  await page.locator('input[type=password]').fill('Browser-Password-42!');
  await page.getByRole('button', { name: /Activer mon Cabinet Syndic/ }).click();
  await expect(page.getByRole('heading', { name: 'Vérifiez votre adresse email' })).toBeVisible({ timeout: 30000 });
  const resend = page.waitForResponse(response => response.url().endsWith('/api/auth/verification/request'));
  await page.getByRole('button', { name: 'Renvoyer le lien' }).click();
  assert.equal((await resend).status(), 200, 'Resend uses the browser Firebase identity');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Vérifiez votre adresse email' })).toBeVisible();
  const codes = (await (await fetch(`http://${emulator}/emulator/v1/projects/demo-buildmanage/oobCodes`)).json()).oobCodes;
  const verification = codes.find((code: any) => code.email === 'browser@example.test' && code.requestType === 'VERIFY_EMAIL');
  assert.ok(verification, 'Verification email was generated by Firebase');
  assert.ok((await fetch(`http://${emulator}/identitytoolkit.googleapis.com/v1/accounts:update?key=demo-key`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ oobCode: verification.oobCode }),
  })).ok);
  await page.getByRole('button', { name: 'Actualiser', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Vérifiez votre adresse email' })).toHaveCount(0);
  await expect(page.getByText('Firebase browser cabinet', { exact: true }).first()).toBeVisible();
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('syndik_auth_session_v1')!));
  assert.equal(data.profile.emailVerified, true, 'Verified profile survives a page refresh');
  assert.deepEqual(failures, [], 'No browser runtime errors');
  console.log('Firebase browser registration, SDK sign-in, resend, persistence and verification passed.');
} catch (error) { console.error(logs); throw error; }
finally { await browser?.close(); child.kill('SIGTERM'); await exited; rmSync(directory, { recursive: true, force: true }); }
